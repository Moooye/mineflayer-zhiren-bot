// ============================================================
// 扫箱指令：建立仓库索引，让后续 !取 / !存箱 能直达目标箱子
//
//   !扫箱 开始     从当前位置开始扫箱（沿途开箱，记录「物品 → 箱子坐标」）
//   !扫箱 继续     断点续传：跳过已扫过的，接着扫
//   !扫箱 状态     看进度（扫了多少、空箱、打不开、还剩）
//   !扫箱 重来     清空索引，从头扫
//   !扫箱 停       停止本次扫描（已扫的会保存）
//
// 为什么需要它：
//   仓库有上千个箱子、每箱只放一种物品时，机器人不可能现场逐个翻
//   （一次要几分钟，还容易被服务器判定异常）。扫一次建立索引后，
//   !取 钻石 就能直接走到装着钻石的那个箱子，1~3 秒完成。
//
// 用法要点：
//   · 扫箱是"后台边走边开箱"，期间机器人会自己走动，请不要同时下别的指令
//   · 索引存在本地 chest-index.json，掉线后发 !扫箱 继续 能接着扫
//   · 换服务器后索引自动按服务器标记区分（不同服不混用）
//
// 权限：control（owner 或被授予控制权限的白名单玩家）
// 仅私聊（whisperOnly）：公屏发来静默忽略
// ============================================================
'use strict'

const 模式词 = {
  '开始': '开始', '开始扫': '开始', '扫': '开始', 'start': '开始',
  '继续': '继续', '接着': '继续', '续传': '继续', 'continue': '继续',
  '重来': '重来', '重新': '重来', '重置': '重来', 'reset': '重来',
  '状态': '状态', '进度': '状态', 'status': '状态',
  '停': '停', '停止': '停', '中止': '停', 'stop': '停',
}

const scanCommand = {
  name: 'scanchest',
  aliases: ['扫箱', '扫描箱子', '建索引'],
  usage: '!扫箱 开始|继续|状态|重来|停',
  permission: 'control',
  whisperOnly: true,
  cooldownMs: 2000,
  async execute ({ args, ctx, reply }) {
    const cm = ctx.services.chestManager
    if (!cm) return reply('箱子功能未装配')

    const 输入 = String(args[0] || '开始').toLowerCase().replace(/\s/g, '')
    const 模式 = 模式词[输入] || '开始'

    if (模式 === '状态') {
      const s = cm.scanStatus()
      if (!s.扫描中) {
        return reply(s.索引箱数 > 0
          ? `索引：已记录 ${s.索引箱数} 个箱子、${s.物品种类} 种物品（存于 ${s.文件}）。发 !扫箱 开始 继续补充，或 !扫箱 重来 清空重建`
          : '还没有索引。站在仓库入口发 !扫箱 开始，机器人会沿途开箱建索引')
      }
      return reply(`扫箱中：已运行 ${s.已运行秒} 秒，本趟扫 ${s.本趟扫} 个（空箱 ${s.本趟空箱}、打不开 ${s.本趟打不开}），索引累计 ${s.索引箱数} 箱 / ${s.物品种类} 种物品。发 !扫箱 停 可停下`)
    }

    if (模式 === '停') return reply(cm.stopScan().message)

    if (模式 === '开始' || 模式 === '继续' || 模式 === '重来') {
      const r = await cm.startScan(模式)
      if (!r.ok) return reply(r.message)
      // 触发后台扫描（不阻塞回复）
      cm.runScan().catch(e => {
        if (ctx.logger) ctx.logger.warn('扫箱过程出错：' + ((e && e.message) || e))
      })
      return reply(r.message)
    }

    return reply('用法：!扫箱 开始 / 继续 / 状态 / 重来 / 停')
  },
}

module.exports = [scanCommand]
